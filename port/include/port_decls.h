/* Prototypes the port needs that the decomp headers leave implicit.
 *
 * Some decomp functions are called before any declaration (implicit `int f()`) and defined later with a narrower
 * type, or declared at block scope and reused elsewhere. gcc 2.8 accepted that; modern gcc rejects it. Adding the
 * prototype to the decomp headers could change PS1 codegen at the call sites, so the port declares them here, per
 * binary (an overlay's func_X is unrelated to another overlay's). On ARM the callee extends narrow return values
 * (AAPCS), so callers that read an int get the same value as on the PS1.
 *
 * port_decls_gen.h is generated by tools/gen_decls.py from the compiler's diagnostics.
 */
#ifndef PORT_DECLS_H
#define PORT_DECLS_H

#include "port_decls_gen.h"

/* ---- hand-written: calls that don't fit any single prototype -------------------------------------------- */

#ifdef PORT_BIN_ovl_0a
/* Defined with 4 parameters, called with 5 (ovl_0a.c ~10295, ~10372). The MIPS callee never reads the 5th. The
 * macro drops it at the call sites and leaves the 4-argument definition unchanged. (Decomp request R1 note.) */
s32 func_800C6C04(u8 *, Unk800C6C04A *, Unk800C6C04B *, s16);
#define func_800C6C04(a, b, c, d, ...) func_800C6C04(a, b, c, d)
#endif

#endif
