#!/usr/bin/env python3
"""Generate port/include/port_decls_gen.h from a build log's implicit-declaration errors.

Usage: gen_decls.py BUILD_LOG [BUILD_LOG ...]

gcc 2.8 accepted a call to an undeclared function followed by a definition with a narrower type (or a block-scope
declaration reused elsewhere); modern gcc rejects both. For each such error this records a file-scope prototype
for that binary, taken from gcc's own diagnostic: the definition's type for "conflicting types", the earlier
declaration's type for "incompatible implicit declaration". Existing entries are kept, so it can be re-run after
each build until the log is clean. The output is committed and reviewed like any other source.
"""
import re
import sys
from pathlib import Path

OUT = Path("port/include/port_decls_gen.h")
CONFLICT = re.compile(r"^decomp/src(?:_equiv)?/(\w+)/[^:]*:\d+:\d+: error: conflicting types for '(\w+)'; have '([^']*)'")
INCOMPAT = re.compile(r"^decomp/src(?:_equiv)?/(\w+)/[^:]*:\d+:\d+: error: incompatible implicit declaration of function '(\w+)'")
NOTE = re.compile(r"note: previous implicit declaration of '(\w+)' with type '([^']*)'")


def proto(name, ftype):
    """'R(A, B)' -> 'R name(A, B);' (the return type is everything before the parameter list's opening paren)."""
    depth = 0
    for i in range(len(ftype) - 1, -1, -1):
        if ftype[i] == ")":
            depth += 1
        elif ftype[i] == "(":
            depth -= 1
            if depth == 0:
                ret, params = ftype[:i].rstrip(), ftype[i:]
                break
    else:
        sys.exit(f"can't parse type {ftype!r} of {name}")
    params = re.sub(r",\s+", ", ", params)
    sep = "" if ret.endswith("*") else " "
    return f"{ret}{sep}{name}{params};"


def load_existing():
    decls = {}
    if OUT.exists():
        cur = None
        for line in OUT.read_text().splitlines():
            m = re.match(r"#ifdef PORT_BIN_(\w+)", line)
            if m:
                cur = m.group(1)
            elif line.startswith("#endif"):
                cur = None
            elif cur and line.strip():
                name = re.search(r"(\w+)\(", line).group(1)
                decls.setdefault(cur, {})[name] = line
    return decls


def main():
    decls = load_existing()
    for log in sys.argv[1:]:
        lines = Path(log).read_text().splitlines()
        for i, line in enumerate(lines):
            m = CONFLICT.match(line)
            if m:
                binary, name, ftype = m.groups()
                decls.setdefault(binary, {})[name] = proto(name, ftype)
                continue
            m = INCOMPAT.match(line)
            if m:
                binary, name = m.groups()
                for later in lines[i + 1 : i + 6]:
                    n = NOTE.search(later)
                    if n and n.group(1) == name:
                        decls.setdefault(binary, {})[name] = proto(name, n.group(2))
                        break
    out = [
        "/* Generated by tools/gen_decls.py from implicit-declaration errors: see port_decls.h. Reviewed; re-run",
        " * the tool rather than editing by hand. */",
        "#ifndef PORT_DECLS_GEN_H",
        "#define PORT_DECLS_GEN_H",
    ]
    for binary in sorted(decls):
        out += ["", f"#ifdef PORT_BIN_{binary}"]
        out += [decls[binary][n] for n in sorted(decls[binary])]
        out += ["#endif"]
    out += ["", "#endif", ""]
    OUT.write_text("\n".join(out))
    print(f"{OUT}: {sum(len(d) for d in decls.values())} prototypes")


if __name__ == "__main__":
    main()
